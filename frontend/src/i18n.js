export function setLanguage(nextLanguage) {
  if (!supportedLanguages.includes(nextLanguage)) return
  language.value = nextLanguage
  globalThis.localStorage?.setItem(STORAGE_KEY, nextLanguage)
  if (globalThis.document) document.documentElement.lang = nextLanguage === 'zh' ? 'zh-CN' : 'en'
}

export function translate(message) {
  if (language.value !== 'zh' || typeof message !== 'string') return message
  return zh[message] || message
}

export function translateCategory(name) {
  return language.value === 'zh' ? categoryZh[name] || name : name
}

export function useI18n() {
  return {
    language,
    locale: computed(() => (language.value === 'zh' ? 'zh-CN' : 'en-US')),
    setLanguage,
    t: translate,
    tc: translateCategory,
  }
}

if (globalThis.document) {
  document.documentElement.lang = language.value === 'zh' ? 'zh-CN' : 'en'
}
